    <script>
        $(document).ready(function () {
            var dropifyInput = $('#dropify').dropify({
                allowedFileExtensions: ['jpg', 'jpeg', 'png', 'pdf', 'doc', 'docx', 'txt', 'xlsx', 'xls', 'zip', 'mp4'],
                messages: {
                    'default': 'فایل را اینجا بکشید یا کلیک کنید',
                    'replace': 'فایل را اینجا بکشید یا کلیک کنید',
                    'remove': 'حذف',
                    'error': 'خطا در بارگزاری فایل'
                },
                error: {
                    'allowedExtension': 'فایل انتخابی مجاز نمی باشد',
                }
            });

            $('body').on('click', '#upload_file', function () {
                var btn = $(this);
                var btn_close = $('#btn_close_upload');
                var btn_cancel = $('#btn_cancel_upload');
                if (dropifyInput.data('dropify').file.name == null) {
                    swal({
                        title: "خطا",
                        text: "لطفا فایل مورد نظر خود را انتخاب کنید",
                        type: "error",
                        showCancelButton: true,
                        allowOutsideClick: true,
                        showConfirmButton: false,
                        cancelButtonText: "متوجه شدم",
                        closeOnConfirm: false
                    });
                    return false;
                }
                btn.addClass('btn-loading btn-light disabled').removeClass('btn-primary');
                btn.attr('disabled', true);
                btn_close.attr('disabled', true);
                btn_close.addClass('op-0-3');
                btn_cancel.attr('disabled', true);
                btn_cancel.addClass('op-0-3');
            @this.dispatch('upload')
                ;
            });

            Livewire.on('upload_complete', () => {
                var btn = $('#upload_file');
                var btn_close = $('#btn_close_upload');
                var btn_cancel = $('#btn_cancel_upload');
                btn.removeClass('btn-loading btn-light disabled').addClass('btn-primary');
                btn.removeAttr('disabled', true);
                btn_close.removeAttr('disabled', true);
                btn_close.removeClass('op-0-3');
                btn_cancel.removeAttr('disabled', true);
                btn_cancel.removeClass('op-0-3');
                //clear dropify
                dropifyInput.data('dropify').resetPreview();
                //close modal upload file
                $('#Vertically').modal('hide');
            });

            $('body').on('click', '.delete', function () {
                var name = $(this).attr('data-name');
                var isDirectory = $(this).attr('data-is-directory');
                var message = "آیا از حذف این فایل به صورت دائم اطمینان دارید؟";
                if (isDirectory) {
                    message = "آیا از حذف این پوشه و تمام محتویان آن به صورت دائم اطمینان دارید؟";
                }
                swal({
                        customClass: {
                            confirmButton: 'btn btn-success',
                            cancelButton: 'btn btn-danger'
                        },
                        buttonsStyling: false,
                        title: "از حذف این مورد اطمینان دارید؟",
                        text: message,
                        type: "warning",
                        showCancelButton: true,
                        confirmButtonClass: "btn btn-danger",
                        confirmButtonText: "بله حذف شود",
                        cancelButtonText: "خیر",
                        closeOnConfirm: true
                    },
                    function () {
                        @this.dispatch('delete', {file: name});
                    });
            });
            $('body').on('click', '.rename', function () {
                var name = $(this).attr('data-name');
            @this.set('fileToRename', name)
                ;
            @this.set('renameTo', name)
                ;
                $('#renameTo').val(name);
                //open modal bootstrap with id #renameDirectory
                $('#renameDirectory').modal('show');
            });

            $('body').on('click', '.copy_me', function () {
                var link = $(this).attr('data-link');
                try {
                    //copy to user clipboard
                    navigator.clipboard.writeText(link).then(function () {
                        //show swal success message
                        swal(
                            {
                                title: "موفق",
                                text: "لینک فایل کپی شد",
                                type: "success",
                                showCancelButton: false,
                                showConfirmButton: false,
                                timer: 1500,
                                closeOnConfirm: false
                            }
                        );
                    });
                } catch (e) {
                    swal({
                        title: "خطا",
                        text: "مرورگر شما کپی را پشتیبانی نمی کند.",
                        type: "error",
                        showCancelButton: true,
                        allowOutsideClick: true,
                        showConfirmButton: false,
                        cancelButtonText: "متوجه شدم",
                        closeOnConfirm: false
                    });
                }
            });
        });

        Livewire.on('close_modal_directory', () => {
            //close boostrap modal
            $('#addDirectory').modal('hide');
        });

        Livewire.on('close_modal_rename', () => {
            //close boostrap modal
            $('#renameDirectory').modal('hide');
        });

        Livewire.on('error_file_manager', (param) => {
            swal({
                title: "خطا",
                text: "" + param.message,
                type: "error",
                showCancelButton: true,
                allowOutsideClick: true,
                showConfirmButton: false,
                cancelButtonText: "متوجه شدم",
                closeOnConfirm: false
            });
        });
    </script>
